package io.github.sx2xoox.mcpl.game.augment.runtime;

import java.io.BufferedReader;
import java.io.IOException;
import java.io.InputStream;
import java.io.InputStreamReader;
import java.nio.charset.StandardCharsets;
import java.util.Collections;
import java.util.HashMap;
import java.util.Map;

import io.github.sx2xoox.mcpl.game.augment.api.AugmentTier;
import net.kyori.adventure.key.Key;
import net.kyori.adventure.text.Component;
import net.kyori.adventure.text.format.NamedTextColor;
import org.jspecify.annotations.Nullable;

/**
 * The glyphs of the resource pack font {@code mcpl:augment_cards} that draw the floating augment cards
 * ({@link OfferCards}). Generated by {@code tools/assetgen/augment_cards.py}; keep the code points and sizes in sync
 * with it ({@code AugmentCardsTest} reads the font). Every centred glyph has its centre on the text line's middle
 * ({@code 2 + ascent - height / 2 = 0}), and its advance is its PNG's width + 1.
 */
public final class CardGlyphs {

    public static final Key FONT = Key.key("mcpl", "augment_cards");
    /** Resource listing augment id → icon code point (written by the generator). */
    public static final String ICON_TABLE = "augment-card-icons.tsv";

    public static final int NEG = 0xE000;
    public static final int POS = 0xE010;
    public static final int FRAME = 0xE100;
    public static final int FRAME_LIT = 0xE108;
    public static final int KEY = 0xE110;
    public static final int KEY_LIT = 0xE118;
    public static final int REROLL = 0xE11E;
    public static final int REROLL_LIT = 0xE11F;
    public static final int RIBBON = 0xE120;
    public static final int BAR = 0xE130;
    public static final int SMALL_KEY = 0xE150;
    public static final int ICON = 0xE200;

    /** Glyph sizes (PNG pixels = font units). */
    public static final int FRAME_W = 112;
    public static final int FRAME_H = 160;
    public static final int ICON_SIZE = 32;
    public static final int KEY_SIZE = 16;
    public static final int RIBBON_W = 176;
    public static final int RIBBON_H = 18;
    public static final int BAR_W = 122;
    public static final int BAR_H = 8;
    public static final int BAR_STEPS = 20;
    /** Small key caps of the hint line, in this order. */
    public static final String SMALL_KEYS = "12345FQ^";

    private static @Nullable Map<String, Integer> icons;

    private CardGlyphs() {
    }

    /** One glyph of the font, white (so the PNG shows as drawn). */
    public static Component glyph(int codePoint) {
        return Component.text(new String(Character.toChars(codePoint))).font(FONT).color(NamedTextColor.WHITE);
    }

    public static Component frame(AugmentTier tier, boolean lit) {
        return glyph((lit ? FRAME_LIT : FRAME) + tier.ordinal());
    }

    /** The key cap of card {@code n} (1-based). */
    public static Component key(int n, boolean lit) {
        return glyph((lit ? KEY_LIT : KEY) + Math.max(0, Math.min(4, n - 1)));
    }

    public static Component reroll(boolean lit) {
        return glyph(lit ? REROLL_LIT : REROLL);
    }

    public static Component ribbon(AugmentTier tier) {
        return glyph(RIBBON + tier.ordinal());
    }

    /** The timer bar showing {@code fraction} (0..1) of the time left. */
    public static Component bar(double fraction) {
        int level = (int) Math.round(Math.max(0, Math.min(1, fraction)) * BAR_STEPS);
        return glyph(BAR + level);
    }

    /** An inline key cap of the hint line: one of {@link #SMALL_KEYS} ('^' = sneak). */
    public static Component smallKey(char key) {
        int index = SMALL_KEYS.indexOf(Character.toUpperCase(key));
        return glyph(SMALL_KEY + Math.max(0, index));
    }

    /** A horizontal space of {@code units} font units (negative moves left). */
    public static Component space(int units) {
        StringBuilder out = new StringBuilder();
        int base = units < 0 ? NEG : POS;
        int rest = Math.abs(units);
        for (int i = 8; i >= 0; i--) {
            while (rest >= (1 << i)) {
                out.appendCodePoint(base + i);
                rest -= 1 << i;
            }
        }
        return Component.text(out.toString()).font(FONT);
    }

    /** The icon of an augment, or null if the pack has none (an augment newer than the pack). */
    public static @Nullable Component icon(String augmentId) {
        Integer cp = icons().get(augmentId);
        return cp == null ? null : glyph(cp);
    }

    /** Augment id → icon code point, from {@link #ICON_TABLE}. */
    public static synchronized Map<String, Integer> icons() {
        Map<String, Integer> table = icons;
        if (table != null) {
            return table;
        }
        Map<String, Integer> read = new HashMap<>();
        try (InputStream in = CardGlyphs.class.getClassLoader().getResourceAsStream(ICON_TABLE)) {
            if (in != null) {
                BufferedReader reader = new BufferedReader(new InputStreamReader(in, StandardCharsets.UTF_8));
                for (String line = reader.readLine(); line != null; line = reader.readLine()) {
                    String[] parts = line.strip().split("\t");
                    if (parts.length == 2 && !line.startsWith("#")) {
                        read.put(parts[0], Integer.parseInt(parts[1], 16));
                    }
                }
            }
        } catch (IOException | NumberFormatException e) {
            // no icons: the cards show the tier gem instead
        }
        icons = Collections.unmodifiableMap(read);
        return icons;
    }
}
