/**
 * Exports the basic attack (평타) looks of representative jobs to tools/assetgen/models/basic_attack_fx.json, the
 * very sprites {@link BasicFx} gives the game, placed and timed the way {@code BasicAttackRunner} plays them: three
 * attacks in a row (plain, critical, finisher) at an enemy in front. tools/assetgen/basic_attack_preview.py draws GIFs
 * from it. Fails while the file is stale; {@code ./gradlew updateBasicAttackFx} rewrites it.
 */
class BasicAttackFxExportTest {

    static final Path OUT = Path.of("tools", "assetgen", "models", "basic_attack_fx.json");
    /** The jobs shown, one of each kind of look. */
    static final List<String> JOBS = List.of("blade", "chef", "batter", "ninja", "archer", "thunder", "earth",
            "bomber", "sniper", "bard");
    /** Ticks a lobbed object or a projectile may fly in the preview. */
    private static final int MAX_FLIGHT = 40;
    private static final Vector3f EYE = new Vector3f(0, 1.62f, 0);

    private MatchHarness h;

    @BeforeEach
    void setUp() {
        // The attack table's sounds need a (mock) server.
        h = MatchHarness.flat();
    }

    @AfterEach
    void tearDown() {
        h.close();
    }

    @Test
    void exportIsUpToDate() throws IOException {
        String json = export();
        if (Boolean.getBoolean("mcpl.updateDocs")) {
            Files.writeString(OUT, json, StandardCharsets.UTF_8);
            return;
        }
        assertTrue(Files.exists(OUT), OUT + " is missing: run ./gradlew updateBasicAttackFx");
        assertEquals(json, Files.readString(OUT, StandardCharsets.UTF_8),
                OUT + " is out of date: run ./gradlew updateBasicAttackFx");
    }

    /** One display in the preview: its world poses tick by tick from {@code start}. */
    private record Shown(Kind kind, String what, int color, int start, List<float[]> frames) {
    }

    /** The scene of one job. */
    private static final class Scene {
        final List<Shown> shown = new ArrayList<>();
        final List<Vector3f> targets = new ArrayList<>();
        int ticks;

        void add(List<FxSprite> sprites, Vector3f anchor, Quaternionfc frame, int at) {
            for (FxSprite sprite : sprites) {
                List<float[]> frames = new ArrayList<>();
                for (Pose pose : sprite.poses()) {
                    frames.add(world(sprite.kind(), pose, anchor, frame));
                }
                shown.add(new Shown(sprite.kind(), what(sprite), sprite.color(), at + sprite.start(), frames));
                ticks = Math.max(ticks, at + sprite.end());
            }
        }

        void hit(BasicAttack attack, Moment moment, Vector3f target, int at, long seed) {
            Vector3f body = new Vector3f(target).add(0, 0.9f, 0);
            Vector3f toward = new Vector3f(body).sub(EYE).setComponent(1, 0);
            add(BasicFx.impact(attack, moment, seed), body, BasicFx.aimFrame(toward.x, 0, toward.z), at);
        }
    }

    static String export() {
        AbilityRegistry registry = new AbilityRegistry();
        BuiltinAbilities.registerAll(registry);
        StringBuilder out = new StringBuilder();
        out.append("{\"note\": \"generated by BasicAttackFxExportTest (./gradlew updateBasicAttackFx): the basic attack "
                + "displays of three attacks in a row (plain, critical, finisher); poses are world [cx, cy, cz, qx, qy, "
                + "qz, qw, sx, sy, sz] (block displays: a centered box), the attacker at the origin facing +z\",\n");
        out.append(" \"jobs\": [");
        for (int j = 0; j < JOBS.size(); j++) {
            BasicAttack attack = BasicAttacks.builtin(JOBS.get(j));
            assertNotNull(attack, JOBS.get(j));
            AbilityRegistry.Entry entry = registry.get(attack.id());
            String title = (entry == null ? attack.id() : entry.info().name()) + " · " + attack.name();
            Scene scene = scene(attack);
            out.append(j == 0 ? "\n" : ",\n");
            out.append("  {\"id\": \"").append(attack.id()).append("\", \"title\": \"").append(title)
                    .append("\", \"shape\": \"").append(attack.shape().key()).append("\", \"cooldown\": ")
                    .append(attack.cooldown()).append(", \"ticks\": ").append(scene.ticks).append(", \"targets\": [");
            for (int t = 0; t < scene.targets.size(); t++) {
                Vector3f target = scene.targets.get(t);
                out.append(t == 0 ? "" : ", ").append('[').append(n(target.x)).append(", ").append(n(target.z))
                        .append(']');
            }
            out.append("],\n   \"sprites\": [");
            for (int s = 0; s < scene.shown.size(); s++) {
                Shown shown = scene.shown.get(s);
                out.append(s == 0 ? "\n" : ",\n").append("    {\"k\": \"").append(shown.kind().name()
                        .toLowerCase(Locale.ROOT)).append("\", \"m\": \"").append(shown.what().replace("\"", "\\\""))
                        .append("\", \"c\": ").append(shown.color()).append(", \"t\": ").append(shown.start())
                        .append(", \"p\": [");
                for (int f = 0; f < shown.frames().size(); f++) {
                    float[] pose = shown.frames().get(f);
                    out.append(f == 0 ? "[" : ", [");
                    for (int i = 0; i < pose.length; i++) {
                        out.append(i == 0 ? "" : ", ").append(n(pose[i]));
                    }
                    out.append(']');
                }
                out.append("]}");
            }
            out.append("]}");
        }
        out.append("\n]}\n");
        return out.toString();
    }

    /** Three attacks in a row, the way the runner plays each shape. */
    private static Scene scene(BasicAttack attack) {
        Scene scene = new Scene();
        float distance = switch (attack.shape()) {
            case SWING, COMBO, NOVA, CONE -> 2.4f;
            case THRUST -> (float) Math.min(attack.range() * 0.7, 4);
            case SHOT -> 8f;
            case PROJECTILE -> (float) Math.min(attack.range() * 0.55, 7);
            case CHAIN, STRIKE -> 6f;
            case LOB -> lobLanding(attack);
        };
        scene.targets.add(new Vector3f(0, 0, distance));
        if (attack.shape() == BasicAttack.Shape.CHAIN) {
            scene.targets.add(new Vector3f(1.8f, 0, distance + 1.4f));
        }
        BasicAttackSettings.Feel feel = BasicAttackSettings.Feel.DEFAULT;
        Moment[] moments = {new Moment(0, false, false, 7), new Moment(1, false, true, 8),
                new Moment(2, feel.isFinisher(2), false, 9)};
        for (int i = 0; i < moments.length; i++) {
            play(scene, attack, moments[i], i * attack.cooldown());
        }
        return scene;
    }

    private static void play(Scene scene, BasicAttack attack, Moment moment, int at) {
        Vector3f target = scene.targets.getFirst();
        Vector3f body = new Vector3f(target).add(0, 0.9f, 0);
        Quaternionf facing = BasicFx.yawFrame(0);
        Vector3f chest = new Vector3f(EYE).sub(0, BasicFx.CHEST_DROP, 0);
        Vector3f aim = new Vector3f(EYE).sub(0, BasicFx.AIM_DROP, 0);
        switch (attack.shape()) {
            case SWING -> {
                scene.add(BasicFx.swing(attack, moment, 0, true), chest, facing, at);
                scene.hit(attack, moment, target, at, 11);
            }
            case COMBO -> {
                for (int i = 0; i < attack.hits(); i++) {
                    int t = at + i * Math.max(1, attack.interval());
                    scene.add(BasicFx.swing(attack, moment, i, i == attack.hits() - 1), chest, facing, t);
                    scene.hit(attack, moment, target, t, 11 + i);
                }
            }
            case THRUST -> {
                scene.add(BasicFx.thrust(attack, moment, attack.range()), aim, facing, at);
                scene.hit(attack, moment, target, at, 11);
            }
            case SHOT -> {
                for (int i = 0; i < attack.hits(); i++) {
                    int t = at + i * Math.max(1, attack.interval());
                    Vector3f muzzle = new Vector3f(EYE).add(0, -0.2f, 0.7f);
                    Vector3f toward = new Vector3f(body).sub(muzzle);
                    scene.add(BasicFx.tracer(attack, moment, toward.length(), i), muzzle,
                            BasicFx.aimFrame(toward.x, toward.y, toward.z), t);
                    scene.hit(attack, moment, target, t, 11 + i);
                }
            }
            case PROJECTILE -> {
                for (int i = 0; i < attack.hits(); i++) {
                    double offset = attack.hits() > 1 && attack.interval() == 0
                            ? -attack.angle() / 2 + attack.angle() * i / (attack.hits() - 1) : 0;
                    int t = at + (attack.interval() > 0 ? i * attack.interval() : 0);
                    Vector3f direction = new Vector3f(0, 0, 1).rotateY((float) Math.toRadians(-offset));
                    fly(scene, attack, moment, new Vector3f(EYE).add(0, -0.15f, 0)
                            .add(new Vector3f(direction).mul(0.4f)), direction, t, false);
                }
            }
            case LOB -> fly(scene, attack, moment, new Vector3f(EYE).add(0, -0.2f, 0.5f), new Vector3f(0, 0, 1), at,
                    true);
            case CHAIN -> {
                Vector3f hand = new Vector3f(EYE).add(0, -0.25f, 0.6f);
                scene.add(BasicFx.bolt(attack, moment, new Vector3f(body).sub(hand), moment.seed()), hand,
                        new Quaternionf(), at);
                scene.hit(attack, moment, target, at, 11);
                Vector3f second = scene.targets.get(1);
                Vector3f secondBody = new Vector3f(second).add(0, 0.9f, 0);
                scene.add(BasicFx.bolt(attack, moment, new Vector3f(secondBody).sub(body), moment.seed() + 1), body,
                        new Quaternionf(), at + 2);
                scene.hit(attack, moment, second, at + 2, 12);
            }
            case CONE -> {
                for (int i = 0; i < attack.hits(); i++) {
                    int t = at + i * Math.max(1, attack.interval());
                    scene.add(BasicFx.cone(attack, moment, i), aim, facing, t);
                    scene.hit(attack, moment, target, t, 11 + i);
                }
            }
            case NOVA -> {
                scene.add(BasicFx.nova(attack, moment), new Vector3f(0, 1, 0), facing, at);
                scene.hit(attack, moment, target, at, 11);
            }
            case STRIKE -> {
                scene.add(BasicFx.telegraph(attack, moment, attack.interval()), target, new Quaternionf(), at);
                scene.add(BasicFx.eruption(attack, moment), target, facing, at + attack.interval());
                scene.hit(attack, moment, target, at + attack.interval(), 11);
            }
        }
    }

    /** A projectile or lob flying from {@code start}: its parts tick by tick, the trail, the hit or burst. */
    private static void fly(Scene scene, BasicAttack attack, Moment moment, Vector3f start, Vector3f direction, int at,
                            boolean lob) {
        Vector3f target = scene.targets.getFirst();
        List<Part> parts = BasicFx.projectile(attack, moment);
        Quaternionf frame = lob ? BasicFx.aimFrame(direction.x, 0, direction.z)
                : BasicFx.aimFrame(direction.x, direction.y, direction.z);
        List<List<float[]>> partFrames = new ArrayList<>();
        for (int i = 0; i < parts.size(); i++) {
            partFrames.add(new ArrayList<>());
        }
        Vector3f position = new Vector3f(start);
        Vector3f velocity = lob ? new Vector3f(direction).mul((float) attack.speed()).add(0, 0.15f, 0)
                : new Vector3f(direction).mul((float) attack.speed());
        float reach = lob ? 0.3f : (float) attack.radius();
        float traveled = 0;
        int tick = 0;
        boolean hit = false;
        while (true) {
            for (int i = 0; i < parts.size(); i++) {
                Part part = parts.get(i);
                partFrames.get(i).add(world(part.kind(), BasicFx.partPose(attack, part, tick), position, frame));
            }
            if (hit || tick >= MAX_FLIGHT || (lob ? position.y <= 0.05f : traveled >= attack.range())) {
                break;
            }
            Vector3f before = new Vector3f(position);
            position.add(velocity);
            traveled += velocity.length();
            if (lob) {
                velocity.y -= 0.06f;
                velocity.mul(0.99f);
                position.y = Math.max(0, position.y);
            }
            tick++;
            hit = Math.abs(position.x - target.x) <= 0.3f + reach && Math.abs(position.z - target.z) <= 0.3f + reach
                    && position.y >= -reach && position.y <= 1.8f + reach;
            Vector3f back = new Vector3f(before).sub(position);
            scene.add(BasicFx.trail(attack, moment, back, tick), new Vector3f(position), new Quaternionf(), at + tick);
        }
        for (int i = 0; i < parts.size(); i++) {
            Part part = parts.get(i);
            List<float[]> frames = partFrames.get(i);
            float[] last = frames.getLast().clone();
            last[7] = last[8] = last[9] = Pose.GONE;
            frames.add(last);
            scene.shown.add(new Shown(part.kind(), part.material().name().toLowerCase(Locale.ROOT), 0, at, frames));
        }
        scene.ticks = Math.max(scene.ticks, at + tick + 2);
        int end = at + tick;
        if (lob) {
            scene.add(BasicFx.splash(attack, moment), new Vector3f(position), new Quaternionf(), end);
        }
        if (hit || lob) {
            scene.hit(attack, moment, target, end, 11);
        }
    }

    /** Where a lob thrown straight ahead at eye height lands (the preview puts the enemy there). */
    private static float lobLanding(BasicAttack attack) {
        Vector3f position = new Vector3f(EYE).add(0, -0.2f, 0.5f);
        Vector3f velocity = new Vector3f(0, 0.15f, (float) attack.speed());
        for (int i = 0; i < MAX_FLIGHT && position.y > 0.05f; i++) {
            position.add(velocity);
            velocity.y -= 0.06f;
            velocity.mul(0.99f);
        }
        return Math.round(position.z * 10) / 10f;
    }

    /** A pose placed at {@code anchor} and turned by {@code frame}: [center, rotation (text: none), size]. */
    private static float[] world(Kind kind, Pose pose, Vector3f anchor, Quaternionfc frame) {
        Vector3f center = frame.transform(new Vector3f(pose.center())).add(anchor);
        Quaternionf rotation = kind == Kind.TEXT ? new Quaternionf() : new Quaternionf(frame).mul(pose.rotation());
        return new float[] {center.x, center.y, center.z, rotation.x, rotation.y, rotation.z, rotation.w,
                pose.size().x(), pose.size().y(), pose.size().z()};
    }

    private static String what(FxSprite sprite) {
        return sprite.kind() == Kind.TEXT ? String.valueOf(sprite.text())
                : sprite.material().name().toLowerCase(Locale.ROOT);
    }

    private static String n(float value) {
        float rounded = Math.round(value * 1000) / 1000f;
        if (rounded == 0) {
            return "0";
        }
        String text = String.format(Locale.ROOT, "%.3f", rounded);
        text = text.contains(".") ? text.replaceAll("0+$", "").replaceAll("\\.$", "") : text;
        return text.equals("-0") ? "0" : text;
    }
}
